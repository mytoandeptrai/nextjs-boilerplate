import { z } from 'zod';

import { CONFIGURATOR_LIMITS } from '@/constants/const';
import { normalizePhone, VN_PHONE_REGEX } from '@/lib/format';

export interface ICheckoutSchemaMessages {
  nameRequired: string;
  phoneInvalid: string;
  tooLong: string;
}

/** Customer fields of the checkout form. Built per locale on the client; the Route Handler uses the same rules. */
export const createCheckoutSchema = (messages: ICheckoutSchemaMessages) =>
  z.object({
    customerName: z.string().trim().min(1, messages.nameRequired).max(120, messages.tooLong),
    customerPhone: z.string().transform(normalizePhone).pipe(z.string().regex(VN_PHONE_REGEX, messages.phoneInvalid)),
    customerAddress: z.string().trim().max(300, messages.tooLong),
    notes: z.string().trim().max(2000, messages.tooLong),
    /** Honeypot: hidden from people, filled by bots. */
    website: z.string().max(200).optional(),
  });

export type CheckoutFormInput = z.input<ReturnType<typeof createCheckoutSchema>>;
export type CheckoutFormData = z.output<ReturnType<typeof createCheckoutSchema>>;

const { width, height, quantity } = CONFIGURATOR_LIMITS;

/** A cart line as the browser sends it: ids and sizes only. Prices are recomputed on the server. */
export const quoteItemSchema = z.object({
  productId: z.uuid(),
  widthCm: z.number().int().min(width.min).max(width.max),
  heightCm: z.number().int().min(height.min).max(height.max),
  pleatId: z.string().max(60).nullable(),
  fullness: z.number(),
  fabricId: z.string().max(60).nullable(),
  motorId: z.string().max(60).nullable(),
  quantity: z.number().int().min(quantity.min).max(quantity.max),
});

export const quoteBodySchema = createCheckoutSchema({
  nameRequired: 'Name is required',
  phoneInvalid: 'Invalid phone number',
  tooLong: 'Too long',
}).extend({
  /** Generated by the browser so the Zalo message, the confirmation and the saved row share one code. */
  id: z.uuid(),
  channel: z.enum(['zalo', 'email']),
  items: z.array(quoteItemSchema).min(1).max(50),
});

export type QuoteBody = z.input<typeof quoteBodySchema>;
